const pad = (n, w) => String(n).padStart(w, '0')
const addDays = (iso, d) => {
  const t = new Date(`${iso}T00:00:00Z`)
  t.setUTCDate(t.getUTCDate() + d)
  return t.toISOString().slice(0, 10)
}

const firs = [...RAW, ...gujaratRaw(S)].map((r, i) => {
  const [seed_group, key, occDate, delay, time_period, place, acts_sections, complainant, accused, victim, narrative, language, mo_summary, status, ioIdx] = r
  const st = STATIONS[key]
  const firDate = addDays(occDate, delay)
  const year = firDate.slice(0, 4)
  const serial = pad(40 + ((i * 37) % 560), 4)
  const [ioName, ioRank] = IO[key][ioIdx ?? 0]
  // deterministic offset so incidents from one station do not stack on a single map point
  const dLat = (((i * 7919) % 21) - 10) / 1000
  const dLng = (((i * 104729) % 21) - 10) / 1000
  return {
    fir_id: `${serial}/${year}`,
    fir_reg_no: `${st.code}${year.slice(2)}${serial}`,
    state: st.state,
    district: st.district,
    police_station: st.ps,
    date_of_fir: `${firDate}T${pad(9 + (i % 9), 2)}:${pad((i * 13) % 60, 2)}:00`,
    occurrence: { date: occDate, time_period, place },
    acts_sections,
    complainant: { name: complainant, phone_masked: `+91-${60 + (i % 39)}XXX${pad((i * 7873) % 100000, 5)}` },
    accused,
    victim_profile: { gender: victim[0], age_range: victim[1], relation_to_accused: victim[2] },
    narrative,
    language,
    mo_summary,
    investigating_officer: { name: ioName, rank: ioRank },
    status,
    lat: +(st.lat + dLat).toFixed(4),
    lng: +(st.lng + dLng).toFixed(4),
    seed_group,
  }
})

const ids = new Set(firs.map((f) => `${f.police_station}|${f.fir_id}`))
if (ids.size !== firs.length) throw new Error('Duplicate FIR id within a station')

const out = resolve(dirname(fileURLToPath(import.meta.url)), '../src/data/firs.json')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, JSON.stringify(firs, null, 2))
console.log(`Wrote ${firs.length} FIRs to ${out}`)
